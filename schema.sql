-- ============================================================================
-- ESQUEMA DE BASE DE DATOS - CONTROL FINANCIERO PERSONAL (COP)
-- ============================================================================

-- 1. Tabla de categorías personalizadas (Ingresos y Gastos)
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('Ingreso', 'Gasto')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT categorias_nombre_tipo_unique UNIQUE (nombre, tipo)
);

-- 2. Tabla principal de movimientos financieros
CREATE TABLE IF NOT EXISTS public.movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    descripcion TEXT NOT NULL,
    categoria TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('Ingreso', 'Gasto')),
    valor NUMERIC(15, 2) NOT NULL CHECK (valor > 0),
    metodo_pago TEXT NOT NULL CHECK (metodo_pago IN ('Efectivo', 'Transferencia', 'Tarjeta', 'Otro')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_movimientos_fecha ON public.movimientos (fecha DESC);
CREATE INDEX IF NOT EXISTS idx_movimientos_tipo ON public.movimientos (tipo);

-- 3. Tabla de presupuestos mensuales
CREATE TABLE IF NOT EXISTS public.presupuestos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes_anio TEXT NOT NULL, -- Formato: YYYY-MM (ej. 2026-11)
    categoria TEXT NOT NULL DEFAULT 'General',
    monto_limite NUMERIC(15, 2) NOT NULL CHECK (monto_limite >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT presupuestos_mes_categoria_unique UNIQUE (mes_anio, categoria)
);

